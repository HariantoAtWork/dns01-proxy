import type { ProxyHost, ProxyLocation } from '../types/proxyHost'

function indent(block: string, spaces = 2): string {
  const pad = ' '.repeat(spaces)
  return block
    .split('\n')
    .map(line => (line.trim() ? `${pad}${line}` : line))
    .join('\n')
}

function locationBlock(location: ProxyLocation): string {
  const lines = [
    `location ${location.path} {`,
    `  proxy_pass ${location.forwardScheme}://${location.forwardHost}:${location.forwardPort};`,
  ]
  if (location.advancedConfig?.trim()) {
    lines.push(indent(location.advancedConfig.trim(), 2))
  }
  lines.push('}')
  return lines.join('\n')
}

/** Export an nginx server snippet for one proxy host (config UI only — not live-applied). */
export function buildNginxSnippet(host: ProxyHost): string {
  const serverNames = host.domainNames.join(' ')
  const lines: string[] = [
    `# Proxy host: ${host.domainNames[0] || host.id}`,
    `# Generated by acmedns-stack plugins/proxy — export only`,
    'server {',
    `  listen 80;`,
    ...(host.certificateName ? ['  listen 443 ssl http2;'] : []),
    `  server_name ${serverNames};`,
    '',
    `  set $forward_scheme ${host.forwardScheme};`,
    `  set $server ${host.forwardHost};`,
    `  set $port ${host.forwardPort};`,
    '',
  ]

  if (host.certificateName) {
    lines.push(
      `  # certificateName: ${host.certificateName}`,
      '  # ssl_certificate     /path/to/fullchain.pem;',
      '  # ssl_certificate_key /path/to/privkey.pem;',
      '',
    )
  }

  if (host.sslForced && host.certificateName) {
    lines.push(
      '  if ($scheme = http) {',
      '    return 301 https://$host$request_uri;',
      '  }',
      '',
    )
  }

  lines.push(
    '  location / {',
    '    proxy_pass $forward_scheme://$server:$port;',
    '    proxy_set_header Host $host;',
    '    proxy_set_header X-Real-IP $remote_addr;',
    '    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
    host.trustForwardedProto
      ? '    proxy_set_header X-Forwarded-Proto $http_x_forwarded_proto;'
      : '    proxy_set_header X-Forwarded-Proto $scheme;',
  )

  if (host.allowWebsocketUpgrade) {
    lines.push(
      '    proxy_set_header Upgrade $http_upgrade;',
      '    proxy_set_header Connection "upgrade";',
    )
  }

  if (host.cachingEnabled) {
    lines.push('    proxy_cache_valid 200 1d;')
  }

  if (host.advancedConfig.trim()) {
    lines.push(indent(host.advancedConfig.trim(), 4))
  }

  lines.push('  }')

  for (const location of host.locations) {
    lines.push('', locationBlock(location))
  }

  lines.push('}')
  return `${lines.join('\n')}\n`
}
